# gen_glide_stubs.sh - build src/glide_stubs.S from tools/glide_exports.txt
#
# lds (i686 PE) strips exactly one leading underscore when it writes the
# export table, so a symbol "__grGlideInit@0" is exported as the
# "_grGlideInit@0" that jsf.exe imports
#
set -e
cd "$(dirname "$0")/.."

out=src/glide_stubs.S
{
  echo '/* generated by tools/gen_glide_stubs.sh - do not edit */'
  echo '	.text'
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    case "$line" in \#*) continue;; esac
    sym="__${line}"
    bytes="${line##*@}"
    echo "	.globl \"$sym\""
    echo "\"$sym\":"
    echo "	xor %eax,%eax"
    echo "	ret \$$bytes"
  done < tools/glide_exports.txt
} > "$out"
echo "wrote $out"
